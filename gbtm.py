    labels    = km.labels_
    centers   = km.cluster_centers_
    group_counts = pd.Series(labels).value_counts().sort_index()
    group_props  = (group_counts / len(labels) * 100).round(1)

    # Sort groups by mean level (low to high)
    group_order = np.argsort(centers.mean(axis=1))

    fig, ax = plt.subplots(figsize=(9, 6))

