# ── Find optimal number of groups using BIC-like criterion ──
def compute_bic(kmeans, X):
    centers = kmeans.cluster_centers_
    labels  = kmeans.labels_
    n_clusters = kmeans.n_clusters
    n_samples, n_features = X.shape

    # Compute variance
    variance = np.sum([np.sum((X[labels == k] - centers[k])**2)
                       for k in range(n_clusters)]) / (n_samples - n_clusters)

    # BIC
    bic = (n_samples * np.log(variance) +
           n_clusters * np.log(n_samples) * n_features)
    return bic

