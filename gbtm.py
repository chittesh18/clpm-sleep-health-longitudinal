# ── Compute means, SE, 95% CI ──────────────────────────────────
def get_stats(data, cols):
    means  = [data[c].mean()  for c in cols]
    sds    = [data[c].std()   for c in cols]
    ns     = [data[c].count() for c in cols]
    ses    = [sd / np.sqrt(n) for sd, n in zip(sds, ns)]
    lower  = [m - 1.96*se    for m, se  in zip(means, ses)]
    upper  = [m + 1.96*se    for m, se  in zip(means, ses)]
    return means, lower, upper

